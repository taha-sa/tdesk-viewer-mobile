const fs = require('fs');
const assert = require('assert');
const ts = require('typescript');
const XLSX = require('xlsx');
const source = fs.readFileSync('src/viewers/SpreadsheetViewer.tsx', 'utf8').split('// @@PURE-START')[1].split('// @@PURE-END')[0];
const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const mod = { exports: {} };
new Function('module', 'exports', 'XLSX', 'foldForSearch', 't', code)(mod, mod.exports, XLSX, s => s.toLocaleLowerCase('tr'), key => key);
const { buildGrid, sortOrder, findCellMatches, gridFromRows, serializeDelimited } = mod.exports;
const g = buildGrid('Test', false, { A1: { t: 's', v: 'Ad' }, B1: { t: 's', v: 'Sayi' }, A2: { t: 's', v: 'Elma' }, B2: { t: 'n', v: 10 }, IV20000: { t: 's', v: 'son' } }, XLSX.utils);
assert.equal(g.rowCount, 20000); assert.equal(g.colCount, 256);
assert.equal(Object.keys(g.cells).length, 3);
assert.equal(g.cells[19999][255], 'son');
assert.equal(g.cells[1][1], '10');
assert.equal(findCellMatches(g.cells, [0, 1, 19999], 256, 'son').matches[0].r, 19999);
assert.deepEqual(sortOrder(g.cells, 3, 0, true, true), [0, 1, 2]);
const csv = gridFromRows('csv', [['a', 'b'], ['1', '2'], ['x', 'y']]);
assert.equal(serializeDelimited(csv.cells, ',', '\n'), 'a,b\n1,2\nx,y\n');
console.log('Sparse spreadsheet, search, sort and CSV preservation tests OK');
